#!/usr/bin/env node
/**
 * Regenerate the WordPiece tokenizer parity fixture.
 *
 *   node scripts/gen-tokenizer-golden.mjs
 *
 * Encodes a few hundred strings with Hugging Face `tokenizers` (the library
 * that produced public/models/minilm/tokenizer.json) and writes the expected
 * ids to src/ai/nlp/__tests__/tokenizer.golden.json. The test there checks the
 * browser tokenizer against it, so CI needs no Python.
 *
 * Requires: python with `pip install tokenizers`. Rerun after changing the
 * tokenizer.json or the phrase lists.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TOKENIZER = join(ROOT, 'public/models/minilm/tokenizer.json')
const OUT = join(ROOT, 'src/ai/nlp/__tests__/tokenizer.golden.json')

const { CAPABILITIES } = await import('../shared/capabilities.js')
const { INTENT_PHRASES } = await import('../shared/intentPhrases.js')

// Real phrases the model embeds or users type.
const phrases = [
  ...CAPABILITIES.flatMap((c) => [c.description, ...(c.examples ?? [])]),
  ...Object.values(INTENT_PHRASES).flat(),
  // First-session corpus prompts (a TS file, so read the literals).
  ...[...readFileSync(join(ROOT, 'shared/firstSessionCorpus.ts'), 'utf8').matchAll(/prompt: (['"])(.*?)\1,/g)].map((m) => m[2]),
]

// Edge cases where a hand-written BERT tokenizer usually drifts.
const edgeCases = [
  // accents and case (strip_accents follows lowercase)
  'café', 'Café au lait', 'naïve résumé', 'Señor Muñoz', 'Zürich Straße', 'ÉCOLE', 'İstanbul', 'Ångström', 'São Paulo',
  'crème brûlée', 'façade', 'coöperate', 'Ελληνικά', 'Привет мир', 'ﬁnance', 'Ⅻ',
  // whitespace and invisible characters
  'tab\tseparated\tvalues', 'line\nbreak', 'crlf\r\nline', 'non\u00a0breaking', 'narrow\u202fno-break', 'en\u2002space', 'em\u2003space',
  'thin\u2009space', 'hair\u200aspace', 'zero\u200bwidth', 'zwj\u200djoiner', 'bom\ufefftext', 'ideographic\u3000space', 'nel\u0085char',
  'line\u2028separator', 'para\u2029separator', '  leading and trailing  ', '', '   ', 'soft\u00adhyphen', 'bell\u0007char', 'null\u0000char',
  'replacement\ufffdchar', 'rtl\u200fmark',
  // punctuation (ASCII, Unicode P*, and symbols that are not punctuation)
  'Sum A1:A10, then sort!', "don't stop", '"quoted"', '“curly quotes”', '‘single’', '¿Qué?', '¡Hola!', '«guillemets»', 'em—dash', 'en–dash',
  '…ellipsis', '§ section', '¶ pilcrow', '• bullet', '・katakana dot', '、ideographic comma', '。period', '【brackets】', '«a»b', 'x‐y',
  // symbols (category S: not split by BertPreTokenizer)
  '€100 and £50', '¥500', '25°C', '© 2026', '™ mark', '± 5', '× 3', '÷ 2', '√ 9', '→ next', '★ star', '♥', '¢', '¤', '¬',
  // numbers and spreadsheet text
  '$1,200.50', '50%', '-3.5', '(500)', '1e10', 'B2:C10', '=SUM(A1:A9)', '=IF(B2>0,"yes","no")', 'Q1-2026', '2026-07-11', '07/11/2026',
  '3.14159', '#REF!', '#DIV/0!', 'SKU-100234', 'item_id', 'snake_case_name', 'camelCaseName', 'PascalCase', 'UPPERCASE', 'e-mail@example.com',
  'https://smartsht.com/app?audit=1',
  // scripts without spaces, CJK, emoji
  '中文测试', '日本語のテキスト', 'ひらがな', 'カタカナ', '한국어 텍스트', 'العربية', 'हिन्दी', 'ไทย', 'mixed中文text', '𠀀rare', '😀', 'hi😀there',
  '👍🏽', '👨‍👩‍👧', '🇺🇸', 'Ｆｕｌｌｗｉｄｔｈ', '１２３',
  // long words and WordPiece splits
  'a'.repeat(100), 'a'.repeat(101), 'supercalifragilisticexpialidocious', 'antidisestablishmentarianism', 'unbelievably', 'tokenization',
  'spreadsheets', 'reorganizing', 'xqzvbnm', 'abc123def', 'aaaa😀aaaa',
  // truncation: over 126 word pieces
  Array.from({ length: 140 }, (_, i) => `word${i}`).join(' '),
  'highlight the cell with the biggest number '.repeat(12),
]

const texts = [...new Set([...phrases, ...edgeCases])]

const py = `
import json, sys
from tokenizers import Tokenizer
tok = Tokenizer.from_file(sys.argv[1])
tok.no_padding()
texts = json.load(sys.stdin)
print(json.dumps([[t, tok.encode(t).ids] for t in texts], ensure_ascii=False))
`
// PYTHONIOENCODING: without it, Windows Python reads stdin as cp1252 and every
// non-ASCII test string arrives mangled.
const stdout = execFileSync('python', ['-c', py, TOKENIZER], {
  input: JSON.stringify(texts),
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
  env: { ...process.env, PYTHONIOENCODING: 'utf-8' },
})
const cases = JSON.parse(stdout)

const header = {
  _comment: 'Generated by scripts/gen-tokenizer-golden.mjs from public/models/minilm/tokenizer.json with Hugging Face tokenizers. Do not edit by hand.',
  cases,
}
writeFileSync(OUT, JSON.stringify(header) + '\n')
console.log(`wrote ${cases.length} cases to ${OUT}`)
